/**
 * Truthful "last modified" for a sitemap entry.
 *
 * `new Date()` here is evaluated at BUILD time, so every deploy rewrote the
 * lastmod of every sitemap URL to "now" -- including pages whose content had
 * not changed in months. Google ignores an inaccurate lastmod and may crawl
 * the site less frequently, because a signal that always says "changed"
 * carries no information.
 *
 * `src/data/sitemap-lastmod.json` maps each route to the date of the last
 * commit that touched the file rendering it -- the real date the content
 * changed. It is generated by `scripts/generate-sitemap-lastmod.mjs` and
 * committed, so the build never depends on git history being available.
 *
 * Database-driven URLs (events, venues, movies, attractions) do not use this:
 * they already carry the row's own `updated_at`, which is the truthful signal
 * for them.
 *
 * A route that is missing from the map falls back to build time -- the
 * previous behaviour -- so a stale map can never drop a URL, only lose
 * precision.
 */
const SITEMAP_LASTMOD_EXACT = sitemapLastmod.exact as Record<string, string>;
const SITEMAP_LASTMOD_TEMPLATES = sitemapLastmod.templates as Record<string, string>;

function lastmodFor(route: string): Date {
  const key = route === '/' ? '/' : route.replace(/\/+$/, '');
  const exact = SITEMAP_LASTMOD_EXACT[key];
  if (exact) return new Date(exact);
  const template = SITEMAP_LASTMOD_TEMPLATES[key];
  if (template) return new Date(template);
  return new Date();
}

/**
 * How many rows to fetch per page when reading the database.
 *
 * Supabase/PostgREST caps a single response, so every list is read in pages
 * and the loop continues until the database says there is nothing left. A
 * hardcoded `.limit(500)` silently DROPPED 203 published events from the
 * sitemap -- including 42 events happening in the next three days -- and the
 * DESC sort that came with it kept the farthest-future events and pushed the
 * soonest ones off the end.
 */
const PAGE_SIZE = 1000;

// Lazy initialization to avoid build-time errors
let _supabase: SupabaseClient | null = null;

function getSupabaseClient(): SupabaseClient | null {
  if (_supabase) return _supabase;
  
  const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const supabaseServiceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
  
  if (!supabaseUrl || !supabaseServiceKey) {
    console.warn('Supabase env vars not available for sitemap generation');
    return null;
  }
  
  _supabase = createClient(supabaseUrl, supabaseServiceKey, {
    auth: {
      autoRefreshToken: false,
      persistSession: false
    }
  });
  
  return _supabase;
}

